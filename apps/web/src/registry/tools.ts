/**
 * How a tool handles data. Drives the privacy badge on every tool page, so it must be accurate.
 * - local-file: reads files you choose, processes them in the browser, never uploads
 * - local: no files; everything you type is processed in the browser
 * - server: files are uploaded to the processing service and deleted after processing
 * - hybrid: browser by default, with an optional, clearly-labelled server mode
 */
export type ProcessingMode = "local-file" | "local" | "server" | "hybrid";

