function converterToTool(def: ConversionDef): ToolMeta {
  return {
    slug: def.slug,
    category: "convert",
    alsoIn: def.alsoIn,
    title: def.title,
    description: def.description,
    keywords: def.keywords,
    icon: "repeat",
    processing: def.engine === "server" ? "server" : "local-file",
    related: def.related ?? [],
    popular: def.popular,
    addedAt: def.addedAt,
    kind: "converter",
    conversionSlug: def.slug,
  };
}

const CONVERTER_TOOLS: ToolMeta[] = CONVERSIONS.filter((c) => c.landing && isConversionAvailable(c)).map(converterToTool);

export const TOOLS: ToolMeta[] = [...STATIC_TOOLS, ...CONVERTER_TOOLS];

const bySlug = new Map(TOOLS.map((t) => [t.slug, t]));

export function getTool(slug: string): ToolMeta | undefined {
  return bySlug.get(slug);
}

export function toolPath(tool: Pick<ToolMeta, "category" | "slug">): string {
  return `/${getCategory(tool.category).path}/${tool.slug}`;
}

export function toolsInCategory(category: CategoryId): ToolMeta[] {
  return TOOLS.filter((t) => t.category === category || t.alsoIn?.includes(category));
}

/** Related tools, resolving slugs and silently skipping any that aren't currently available. */
export function relatedTools(tool: ToolMeta, limit = 6): ToolMeta[] {
  return tool.related
    .map((slug) => bySlug.get(slug))
    .filter((t): t is ToolMeta => Boolean(t))
    .slice(0, limit);
}

export function popularTools(): ToolMeta[] {
  return TOOLS.filter((t) => t.popular);
}

/** 301 redirects for alternative category paths and aliases → canonical URL. */
export function toolRedirects(): { source: string; destination: string }[] {
  const out: { source: string; destination: string }[] = [];
  for (const tool of TOOLS) {
    const destination = toolPath(tool);
    for (const cat of tool.alsoIn ?? []) {
      out.push({ source: `/${getCategory(cat).path}/${tool.slug}`, destination });
    }
    for (const alias of tool.aliases ?? []) out.push({ source: alias, destination });
  }
  return out.filter((r) => r.source !== r.destination);
}
