// Generates apps/web/render.yaml, the Render Blueprint for the static site: build settings, public
// build variables, security/caching headers and 301s. Render reads headers and redirects from the
// Blueprint, not from the _headers/_redirects files in out/.
//
//   pnpm build && pnpm render:blueprint   rewrite render.yaml (commit the result)
//   node scripts/render-blueprint.mjs     check only; runs in postbuild on Render (RENDER is set)
//
// Change public build variables in PUBLIC_ENV below, not in the Render dashboard: the CSP is baked
// into render.yaml from these values, so the check fails if the dashboard disagrees.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dump } from "js-yaml";
import { securityHeaders } from "../security-headers.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const blueprintPath = join(root, "render.yaml");

/** Public build variables. Values here are compiled into the pages and the CSP. */
const PUBLIC_ENV = {
  NODE_VERSION: "22.22.2",
  COREPACK_ENABLE_DOWNLOAD_PROMPT: "0",
  // Render's own install runs `pnpm install --prod false`, which pnpm 12 rejects; buildCommand installs.
  SKIP_INSTALL_DEPS: "true",
  NEXT_PUBLIC_SITE_URL: "https://expensico.com",
};
/** Set in the Render dashboard when the Blueprint is created (they don't affect headers). */
const DASHBOARD_ENV = ["NEXT_PUBLIC_OPERATOR_COUNTRY", "NEXT_PUBLIC_LEGAL_JURISDICTION", "NEXT_PUBLIC_LEGAL_EFFECTIVE_DATE"];
/** Build variables that change the CSP; they must come from PUBLIC_ENV so render.yaml matches. */
const CSP_ENV = ["NEXT_PUBLIC_PROCESSOR_URL", "NEXT_PUBLIC_ANALYTICS_PROVIDER", "NEXT_PUBLIC_ANALYTICS_SCRIPT_URL", "NEXT_PUBLIC_ADSENSE_CLIENT", "NEXT_PUBLIC_TURNSTILE_SITE_KEY"];

const CACHE_WEEK = "public, max-age=604800, stale-while-revalidate=86400";

function blueprint() {
  const redirectsFile = join(root, "out/_redirects");
  if (!existsSync(redirectsFile)) throw new Error("out/_redirects not found — run `pnpm build` first");
  const routes = readFileSync(redirectsFile, "utf8")
    .trim()
    .split("\n")
    .map((line) => line.split(" "))
    .map(([source, destination]) => ({ type: "redirect", source, destination }));

  const headers = [
    ...securityHeaders({ env: PUBLIC_ENV }).map(({ key, value }) => ({ path: "/*", name: key, value })),
    { path: "/_next/static/*", name: "Cache-Control", value: "public, max-age=31536000, immutable" },
    { path: "/pdfjs/*", name: "Cache-Control", value: CACHE_WEEK },
    { path: "/icons/*", name: "Cache-Control", value: CACHE_WEEK },
    // Extensionless in the export; without this it would be served as application/octet-stream.
    { path: "/opengraph-image", name: "Content-Type", value: "image/png" },
    { path: "/opengraph-image", name: "Cache-Control", value: "public, max-age=86400" },
  ];

  const service = {
    type: "web",
    name: "expensico-web",
    runtime: "static",
    buildCommand: "corepack pnpm install --frozen-lockfile && corepack pnpm --filter web build",
    staticPublishPath: "./apps/web/out",
    buildFilter: { paths: ["apps/web/**", "packages/**", "package.json", "pnpm-lock.yaml", "pnpm-workspace.yaml"] },
    envVars: [...Object.entries(PUBLIC_ENV).map(([key, value]) => ({ key, value })), ...DASHBOARD_ENV.map((key) => ({ key, sync: false }))],
    headers,
    routes,
  };

  return [
    "# Render Blueprint for the website (static site). GENERATED by scripts/render-blueprint.mjs —",
    "# edit that script, security-headers.mjs or the tool registry, then run `pnpm render:blueprint`.",
    "# In Render: New → Blueprint → this repo, Blueprint Path `apps/web/render.yaml`.",
    "# (The repo-root render.yaml is the paid processor service; keep it out of this Blueprint.)",
    dump({ services: [service] }, { lineWidth: -1, noRefs: true }),
  ].join("\n");
}

const expected = blueprint();

if (process.argv.includes("--write")) {
  writeFileSync(blueprintPath, expected);
  console.log("Wrote render.yaml");
} else if (process.env.RENDER) {
  const problems = [];
  if (!existsSync(blueprintPath) || readFileSync(blueprintPath, "utf8") !== expected) {
    problems.push("render.yaml is out of date: run `pnpm build && pnpm render:blueprint` locally and commit it.");
  }
  for (const key of CSP_ENV) {
    if ((process.env[key] ?? "") !== (PUBLIC_ENV[key] ?? "")) {
      problems.push(`${key} differs from PUBLIC_ENV in scripts/render-blueprint.mjs; set it there (it changes the CSP), not in the dashboard.`);
    }
  }
  if (problems.length) throw new Error(problems.join("\n"));
  console.log("render.yaml is up to date");
}
